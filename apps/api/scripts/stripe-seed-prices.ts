/**
 * Stripe Price Seeder
 *
 * Creates products and recurring prices for all subscription tiers in Stripe,
 * then writes the price IDs to apps/api/.env.
 *
 * Idempotent: safe to re-run. Reuses existing products/prices by metadata.
 *
 * Usage:
 *   pnpm --filter @fitflow/api stripe:seed
 */

import "dotenv/config";
import Stripe from "stripe";
import { readFileSync, writeFileSync, existsSync } from "fs";
import { resolve } from "path";
import {
    TIER_ORDER,
    TIER_PRICING,
    type SubscriptionTier,
    type BillingCurrency,
    type BillingInterval,
} from "@fitflow/shared";

const STRIPE_SECRET_KEY = process.env.STRIPE_SECRET_KEY;
if (!STRIPE_SECRET_KEY) {
    console.error("STRIPE_SECRET_KEY is not set in .env");
    process.exit(1);
}

const stripe = new Stripe(STRIPE_SECRET_KEY, {
    apiVersion: "2025-02-24.acacia",
});

const ENV_PATH = resolve(__dirname, "../.env");

const CURRENCIES: BillingCurrency[] = ["usd", "gbp"];
const INTERVALS: { key: BillingInterval; stripe: Stripe.Price.Recurring.Interval }[] = [
    { key: "MONTHLY", stripe: "month" },
    { key: "ANNUAL", stripe: "year" },
];

const TIER_NAMES: Record<SubscriptionTier, string> = {
    STARTER: "FitFlow Starter",
    PRO: "FitFlow Pro",
    STUDIO: "FitFlow Studio",
};

const TIER_DESCRIPTIONS: Record<SubscriptionTier, string> = {
    STARTER: "Coaching essentials for trainers getting started",
    PRO: "Full-featured coaching platform with payments and analytics",
    STUDIO: "White-label coaching platform for growing teams",
};

async function findExistingProduct(tier: SubscriptionTier): Promise<Stripe.Product | null> {
    const products = await stripe.products.list({ limit: 100, active: true });
    return products.data.find((p) => p.metadata.fitflow_tier === tier) || null;
}

async function getOrCreateProduct(tier: SubscriptionTier): Promise<Stripe.Product> {
    const existing = await findExistingProduct(tier);
    if (existing) {
        console.log(`  Reusing product: ${existing.name} (${existing.id})`);
        return existing;
    }

    const product = await stripe.products.create({
        name: TIER_NAMES[tier],
        description: TIER_DESCRIPTIONS[tier],
        metadata: { fitflow_tier: tier },
    });
    console.log(`  Created product: ${product.name} (${product.id})`);
    return product;
}

async function findExistingPrice(
    productId: string,
    currency: string,
    interval: Stripe.Price.Recurring.Interval,
    amount: number
): Promise<Stripe.Price | null> {
    const prices = await stripe.prices.list({
        product: productId,
        currency,
        type: "recurring",
        active: true,
        limit: 100,
    });

    return (
        prices.data.find(
            (p) =>
                p.recurring?.interval === interval &&
                p.unit_amount === amount
        ) || null
    );
}

async function getOrCreatePrice(
    productId: string,
    tier: SubscriptionTier,
    currency: BillingCurrency,
    interval: { key: BillingInterval; stripe: Stripe.Price.Recurring.Interval },
    amountCents: number
): Promise<Stripe.Price> {
    const existing = await findExistingPrice(productId, currency, interval.stripe, amountCents);
    if (existing) {
        console.log(`    Reusing price: ${tier} ${currency.toUpperCase()} ${interval.key} (${existing.id})`);
        return existing;
    }

    const price = await stripe.prices.create({
        product: productId,
        currency,
        unit_amount: amountCents,
        recurring: { interval: interval.stripe },
        metadata: {
            fitflow_tier: tier,
            fitflow_interval: interval.key,
        },
    });
    console.log(`    Created price: ${tier} ${currency.toUpperCase()} ${interval.key} = ${price.id}`);
    return price;
}

function getAnnualAmount(monthlyPerMonthCents: number): number {
    return monthlyPerMonthCents * 12;
}

function writeEnvVars(envVars: Record<string, string>): void {
    let content = "";
    if (existsSync(ENV_PATH)) {
        content = readFileSync(ENV_PATH, "utf-8");
    }

    // Remove existing STRIPE_PRICE_* lines
    const lines = content.split("\n");
    const filtered = lines.filter((line) => !line.startsWith("STRIPE_PRICE_"));

    // Remove trailing blank lines then add one
    while (filtered.length > 0 && filtered[filtered.length - 1].trim() === "") {
        filtered.pop();
    }
    filtered.push("");

    // Append new vars
    filtered.push("# Stripe Subscription Price IDs (generated by pnpm stripe:seed)");
    for (const [key, value] of Object.entries(envVars)) {
        filtered.push(`${key}=${value}`);
    }
    filtered.push("");

    writeFileSync(ENV_PATH, filtered.join("\n"), "utf-8");
    console.log(`\nWrote ${Object.keys(envVars).length} price IDs to ${ENV_PATH}`);
}

async function main() {
    console.log("Stripe Price Seeder");
    console.log("=".repeat(50));

    if (STRIPE_SECRET_KEY!.startsWith("sk_live")) {
        console.warn("\nWARNING: You are using a LIVE Stripe key.");
        console.warn("Products and prices will be created in your live account.\n");
    }

    const envVars: Record<string, string> = {};

    for (const tier of TIER_ORDER) {
        console.log(`\n${TIER_NAMES[tier]}:`);
        const product = await getOrCreateProduct(tier);

        for (const currency of CURRENCIES) {
            const pricing = TIER_PRICING[currency][tier];

            for (const interval of INTERVALS) {
                const amount =
                    interval.key === "ANNUAL"
                        ? getAnnualAmount(pricing.annual)
                        : pricing.monthly;

                const price = await getOrCreatePrice(
                    product.id,
                    tier,
                    currency,
                    interval,
                    amount
                );

                const envKey = `STRIPE_PRICE_${tier}_${currency.toUpperCase()}_${interval.key}`;
                envVars[envKey] = price.id;
            }
        }
    }

    writeEnvVars(envVars);

    console.log("\nSummary:");
    console.log("-".repeat(50));
    for (const [key, value] of Object.entries(envVars)) {
        console.log(`  ${key} = ${value}`);
    }
    console.log("\nDone!");
}

main().catch((err) => {
    console.error("Seed failed:", err.message);
    process.exit(1);
});
